<?php

declare(strict_types=1);

namespace WebhookGuardian\Tests;

use PDO;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use WebhookGuardian\{Claim, Clock, Guardian, JsonEventId, Verifier};
use WebhookGuardian\Exception\{InvalidEvent, InvalidSignature, PayloadConflict, TimestampOutOfRange};
use WebhookGuardian\Store\PdoSqliteEventStore;

final class GuardianTest extends TestCase
{
    private const SECRET = 'test-only-secret-use-random-bytes-in-production';
    private const NOW = 1700000000;
    private PDO $pdo;
    private PdoSqliteEventStore $store;

    protected function setUp(): void
    {
        $this->pdo = new PDO('sqlite::memory:', options: [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $this->store = new PdoSqliteEventStore($this->pdo);
        $this->store->install();
    }

    private function verifier(array $secrets = [self::SECRET], int $tolerance = 300): Verifier
    {
        return new Verifier($secrets, $tolerance, new class implements Clock {
            public function now(): int { return 1700000000; }
        });
    }

    private function header(string $body, int $timestamp = self::NOW, string $secret = self::SECRET): string
    {
        return 't=' . $timestamp . ',v1=' . hash_hmac('sha256', $timestamp . '.' . $body, $secret);
    }

    private function receive(string $body, string $scope = 'payments'): \WebhookGuardian\Delivery
    {
        return (new Guardian($this->verifier(), $this->store, $scope))
            ->receive($body, $this->header($body), new JsonEventId());
    }

    public function testKnownHmacVector(): void
    {
        // Fixed external Python hmac/hashlib vector, not generated by the verifier.
        $body = '{"id":"evt_1"}';
        self::assertSame(self::NOW, $this->verifier(['secret'])->verify(
            $body,
            't=1700000000,v1=af784f27423c462e20039559cd4264140f7b7ed4c9090e26fd663faa5eeb8dda',
        ));
    }

    public function testExactBodyIncludesWhitespaceUnicodeAndNullBytes(): void
    {
        $body = "{ \"id\": \"é\" }\n\0";
        self::assertSame(self::NOW, $this->verifier()->verify($body, $this->header($body)));
        $this->expectException(InvalidSignature::class);
        $this->verifier()->verify(rtrim($body, "\0\n"), $this->header($body));
    }

    public function testSignatureIsBoundToTimestamp(): void
    {
        $body = '{"id":"evt_1"}';
        $header = str_replace('t=1700000000,', 't=1700000001,', $this->header($body));
        $this->expectException(InvalidSignature::class);
        $this->verifier()->verify($body, $header);
    }

    public function testBothRotationKeysWorkAndRemovedKeyFails(): void
    {
        $body = 'bytes';
        foreach (['old', 'new'] as $secret) {
            self::assertSame(self::NOW, $this->verifier(['new', 'old'])->verify($body, $this->header($body, secret: $secret)));
        }
        $this->expectException(InvalidSignature::class);
        $this->verifier(['new'])->verify($body, $this->header($body, secret: 'old'));
    }

    public static function malformedHeaders(): iterable
    {
        foreach (['', 'v1=x', 't=1,v1=x', 't=-1,v1=', 't=01,v1=', 't=1.0,v1=',
            't=1e9,v1=', 't=9223372036854775808,v1=', 't=1, v1=', 't=1,v1=',
            't=1,t=1,v1=', 'v1=HASH,t=1', 't=1,v2=', 't=1,v1=HASH,v1=HASH',
            "t=1,v1=HASH\n", 't=1,v1=UPPER'] as $header) {
            yield [$header];
        }
    }

    #[DataProvider('malformedHeaders')]
    public function testRejectsAmbiguousOrMalformedHeaders(string $header): void
    {
        $header = str_replace(['HASH', 'UPPER'], [str_repeat('a', 64), str_repeat('A', 64)], $header);
        $this->expectException(InvalidSignature::class);
        $this->verifier()->verify('body', $header);
    }

    public static function timestampOffsets(): iterable
    {
        yield [-301, false]; yield [-300, true]; yield [0, true]; yield [300, true]; yield [301, false];
    }

    #[DataProvider('timestampOffsets')]
    public function testSymmetricTimeWindow(int $offset, bool $valid): void
    {
        if (!$valid) { $this->expectException(TimestampOutOfRange::class); }
        self::assertSame(self::NOW + $offset, $this->verifier()->verify('body', $this->header('body', self::NOW + $offset)));
    }

    public function testZeroTolerance(): void
    {
        self::assertSame(self::NOW, $this->verifier(tolerance: 0)->verify('', $this->header('')));
        $this->expectException(TimestampOutOfRange::class);
        $this->verifier(tolerance: 0)->verify('', $this->header('', self::NOW + 1));
    }

    public function testAuthenticationPrecedesExtractorAndPersistence(): void
    {
        $called = false;
        $guardian = new Guardian($this->verifier(), $this->store, 'payments');
        try {
            $guardian->receive('{"id":"x"}', $this->header('different'), function () use (&$called): string {
                $called = true;
                return 'x';
            });
            self::fail('Must reject invalid signature');
        } catch (InvalidSignature) {
            self::assertFalse($called);
            self::assertSame(0, (int) $this->pdo->query('SELECT COUNT(*) FROM webhook_guardian_events')->fetchColumn());
        }
    }

    public function testExpiredReplayCannotReachExtractor(): void
    {
        $this->expectException(TimestampOutOfRange::class);
        (new Guardian($this->verifier(), $this->store, 'p'))->receive('x', $this->header('x', self::NOW - 301),
            static function (): string { self::fail('Extractor must not execute'); });
    }

    public function testMatchingReplayAndScopeIsolation(): void
    {
        $body = '{"id":"evt_1","amount":100}';
        self::assertSame(Claim::Accepted, $this->receive($body)->claim);
        self::assertSame(Claim::Duplicate, $this->receive($body)->claim);
        self::assertSame(Claim::Accepted, $this->receive($body, 'another-account')->claim);
        // Freshly signed retransmission of identical bytes is still a duplicate.
        self::assertSame(Claim::Duplicate, (new Guardian($this->verifier(), $this->store, 'payments'))
            ->receive($body, $this->header($body, self::NOW + 10), new JsonEventId())->claim);
    }

    public function testConflictDoesNotOverwriteOriginal(): void
    {
        $body = '{"id":"evt_1","amount":100}';
        $this->receive($body);
        try {
            $this->receive('{"id":"evt_1","amount":999}');
            self::fail('Expected conflict');
        } catch (PayloadConflict) {
            self::assertSame(Claim::Duplicate, $this->receive($body)->claim);
        }
    }

    public static function invalidBodies(): iterable
    {
        foreach (['bad json', '[]', '{}', '{"id":1}', '{"id":null}', '{"id":""}', '{"id":"a\\u0000b"}',
            '{"id":"' . str_repeat('x', 256) . '"}'] as $body) { yield [$body]; }
    }

    #[DataProvider('invalidBodies')]
    public function testInvalidIdsNeverReserveRecords(string $body): void
    {
        try { $this->receive($body); self::fail('Expected invalid event'); }
        catch (InvalidEvent) {
            self::assertSame(0, (int) $this->pdo->query('SELECT COUNT(*) FROM webhook_guardian_events')->fetchColumn());
        }
    }

    public function testRollbackAllowsRetryAndCommitCouplesEffects(): void
    {
        $this->pdo->exec('CREATE TABLE effects (event_id TEXT PRIMARY KEY)');
        $body = '{"id":"evt_rollback"}';
        $this->pdo->beginTransaction();
        self::assertSame(Claim::Accepted, $this->receive($body)->claim);
        $this->pdo->exec("INSERT INTO effects VALUES ('evt_rollback')");
        self::assertTrue($this->pdo->inTransaction());
        $this->pdo->rollBack();
        self::assertSame(0, (int) $this->pdo->query('SELECT COUNT(*) FROM effects')->fetchColumn());
        $this->pdo->beginTransaction();
        self::assertSame(Claim::Accepted, $this->receive($body)->claim);
        $this->pdo->exec("INSERT INTO effects VALUES ('evt_rollback')");
        $this->pdo->commit();
        self::assertSame(Claim::Duplicate, $this->receive($body)->claim);
        self::assertSame(1, (int) $this->pdo->query('SELECT COUNT(*) FROM effects')->fetchColumn());
    }

    public function testStorageErrorsPropagateFailClosed(): void
    {
        $this->pdo->exec('DROP TABLE webhook_guardian_events');
        $this->expectException(\PDOException::class);
        $this->receive('{"id":"x"}');
    }

    public function testPersistenceAcrossConnections(): void
    {
        $path = tempnam(sys_get_temp_dir(), 'guardian-');
        try {
            $a = new PdoSqliteEventStore(new PDO('sqlite:' . $path));
            $a->install();
            self::assertSame(Claim::Accepted, $a->claim('s', 'x', hash('sha256', 'a'), 1));
            unset($a);
            $b = new PdoSqliteEventStore(new PDO('sqlite:' . $path));
            self::assertSame(Claim::Duplicate, $b->claim('s', 'x', hash('sha256', 'a'), 2));
        } finally { unlink($path); }
    }
}
